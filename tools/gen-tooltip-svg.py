"""Regenerate the Plasma tooltip frames (widgets/tooltip.svg and the solid / opaque / translucent
variants) with a corner radius that suits small tooltips.

With 32 px corners a one-line tooltip (~42 px high) is smaller than two corners, so KSvg squashes
them and the square shadow tiles stick out behind the curve. The frame, the blur mask and the
shadow are generated from the same radius so they always line up.

  gen-tooltip-svg.py [--radius 12] FILE...      (rewrites each FILE in place, keeping its colours)
"""
import argparse
import re

SHADOW = 10   # shadow thickness
EDGE = 80     # length of the stretchable edge tiles
MARGIN = 12   # content margin hints
K = 0.33      # positions of the shadow fade stops (as in the original theme)


def build(style_block, fill_opacity, R):
    F = 2 * R + EDGE
    C = SHADOW + R
    y0 = F + 16          # mask section
    x0 = F + 16          # shadow section
    y1 = y0 + R + EDGE
    W = x0 + 2 * C + EDGE
    H = max(y0 + F, 2 * C + EDGE)
    m = 0.75
    o1, o2, o3 = R / C, (R + K * SHADOW) / C, (R + 2 * K * SHADOW) / C
    bg = f'class="ColorScheme-Background" style="fill:currentColor; fill-opacity:{fill_opacity};"'
    t = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{W}" height="{H}" version="1.1">
  <!-- generated by tools/gen-tooltip-svg.py (corner radius {R}px) -->
  <defs id="defs-plasma-frame">
    {style_block}
    <linearGradient id="shadow-linear">
      <stop offset="0" stop-color="#000000" stop-opacity="0.28" />
      <stop offset="0.33" stop-color="#000000" stop-opacity="0.14" />
      <stop offset="0.66" stop-color="#000000" stop-opacity="0.05" />
      <stop offset="1" stop-color="#000000" stop-opacity="0" />
    </linearGradient>
    <linearGradient id="sh-top-grad" x1="0" y1="{SHADOW}" x2="0" y2="0" gradientUnits="userSpaceOnUse" xlink:href="#shadow-linear" />
    <linearGradient id="sh-bottom-grad" x1="0" y1="{R}" x2="0" y2="{C}" gradientUnits="userSpaceOnUse" xlink:href="#shadow-linear" />
    <linearGradient id="sh-left-grad" x1="{SHADOW}" y1="0" x2="0" y2="0" gradientUnits="userSpaceOnUse" xlink:href="#shadow-linear" />
    <linearGradient id="sh-right-grad" x1="{R}" y1="0" x2="{C}" y2="0" gradientUnits="userSpaceOnUse" xlink:href="#shadow-linear" />
    <linearGradient id="shadow-corner-stops">
      <stop offset="0" stop-color="#000000" stop-opacity="0.28" />
      <stop offset="{o1:.5f}" stop-color="#000000" stop-opacity="0.28" />
      <stop offset="{o2:.5f}" stop-color="#000000" stop-opacity="0.14" />
      <stop offset="{o3:.5f}" stop-color="#000000" stop-opacity="0.05" />
      <stop offset="1" stop-color="#000000" stop-opacity="0" />
    </linearGradient>
    <radialGradient id="sh-radial-tl" cx="{C}" cy="{C}" r="{C}" fx="{C}" fy="{C}" gradientUnits="userSpaceOnUse" xlink:href="#shadow-corner-stops" />
    <radialGradient id="sh-radial-tr" cx="0" cy="{C}" r="{C}" fx="0" fy="{C}" gradientUnits="userSpaceOnUse" xlink:href="#shadow-corner-stops" />
    <radialGradient id="sh-radial-bl" cx="{C}" cy="0" r="{C}" fx="{C}" fy="0" gradientUnits="userSpaceOnUse" xlink:href="#shadow-corner-stops" />
    <radialGradient id="sh-radial-br" cx="0" cy="0" r="{C}" fx="0" fy="0" gradientUnits="userSpaceOnUse" xlink:href="#shadow-corner-stops" />
  </defs>

  <!-- frame -->
  <path id="topleft" {bg} d="M {R},0 A {R} {R} 0 0 0 0,{R} H {R} Z" />
  <rect id="top" {bg} x="{R}" y="0" width="{EDGE}" height="{R}" />
  <path id="topright" {bg} d="M {R + EDGE},0 A {R} {R} 0 0 1 {F},{R} H {R + EDGE} Z" />
  <rect id="left" {bg} x="0" y="{R}" width="{R}" height="{EDGE}" />
  <rect id="center" {bg} x="{R}" y="{R}" width="{EDGE}" height="{EDGE}" />
  <rect id="right" {bg} x="{R + EDGE}" y="{R}" width="{R}" height="{EDGE}" />
  <path id="bottomleft" {bg} d="M 0,{R + EDGE} A {R} {R} 0 0 0 {R},{F} V {R + EDGE} Z" />
  <rect id="bottom" {bg} x="{R}" y="{R + EDGE}" width="{EDGE}" height="{R}" />
  <path id="bottomright" {bg} d="M {F},{R + EDGE} A {R} {R} 0 0 1 {R + EDGE},{F} V {R + EDGE} Z" />
  <rect id="hint-top-margin" x="{F // 2 - 4}" y="0" width="8" height="{MARGIN}" fill="none" opacity="0.001" />
  <rect id="hint-bottom-margin" x="{F // 2 - 4}" y="{F - MARGIN}" width="8" height="{MARGIN}" fill="none" opacity="0.001" />
  <rect id="hint-left-margin" x="0" y="{F // 2 - 4}" width="{MARGIN}" height="8" fill="none" opacity="0.001" />
  <rect id="hint-right-margin" x="{F - MARGIN}" y="{F // 2 - 4}" width="{MARGIN}" height="8" fill="none" opacity="0.001" />

  <!-- blur / contrast mask (inset {m}px so the blur never bleeds past the anti-aliased edge) -->
  <path id="mask-topleft" fill="#000000" d="M {m},{y0 + R} H 0 H {R} V {y0} V {y0 + m} A {R - m} {R - m} 0 0 0 {m},{y0 + R} Z" />
  <rect id="mask-top" fill="#000000" x="{R}" y="{y0}" width="{EDGE}" height="{R}" />
  <path id="mask-topright" fill="#000000" d="M {F - m},{y0 + R} H {F} H {F - R} V {y0} V {y0 + m} A {R - m} {R - m} 0 0 1 {F - m},{y0 + R} Z" />
  <rect id="mask-left" fill="#000000" x="0" y="{y0 + R}" width="{R}" height="{EDGE}" />
  <rect id="mask-center" fill="#000000" x="{R}" y="{y0 + R}" width="{EDGE}" height="{EDGE}" />
  <rect id="mask-right" fill="#000000" x="{R + EDGE}" y="{y0 + R}" width="{R}" height="{EDGE}" />
  <path id="mask-bottomleft" fill="#000000" d="M {m},{y1} H 0 H {R} V {y0 + F} V {y0 + F - m} A {R - m} {R - m} 0 0 1 {m},{y1} Z" />
  <rect id="mask-bottom" fill="#000000" x="{R}" y="{y1}" width="{EDGE}" height="{R}" />
  <path id="mask-bottomright" fill="#000000" d="M {F - m},{y1} H {F} H {F - R} V {y0 + F} V {y0 + F - m} A {R - m} {R - m} 0 0 0 {F - m},{y1} Z" />

  <!-- shadow ({SHADOW}px outside, {R}px transparent part under the frame) -->
  <g id="shadow-topleft" transform="translate({x0}, 0)">
    <path fill="url(#sh-radial-tl)" d="M 0,0 H {C} V {SHADOW} A {R} {R} 0 0 0 {SHADOW},{C} H 0 Z" />
    <path d="M {SHADOW},{C} A {R} {R} 0 0 1 {C},{SHADOW} V {C} H {SHADOW} Z" opacity="0.001" fill="#000000" />
  </g>
  <g id="shadow-top" transform="translate({x0 + C}, 0)">
    <rect x="0" y="0" width="{EDGE}" height="{SHADOW}" fill="url(#sh-top-grad)" />
    <rect x="0" y="{SHADOW}" width="{EDGE}" height="{R}" opacity="0.001" fill="#000000" />
  </g>
  <g id="shadow-topright" transform="translate({x0 + C + EDGE}, 0)">
    <path fill="url(#sh-radial-tr)" d="M 0,0 H {C} V {C} H {R} A {R} {R} 0 0 0 0,{SHADOW} Z" />
    <path d="M 0,{SHADOW} A {R} {R} 0 0 1 {R},{C} H 0 Z" opacity="0.001" fill="#000000" />
  </g>
  <g id="shadow-left" transform="translate({x0}, {C})">
    <rect x="0" y="0" width="{SHADOW}" height="{EDGE}" fill="url(#sh-left-grad)" />
    <rect x="{SHADOW}" y="0" width="{R}" height="{EDGE}" opacity="0.001" fill="#000000" />
  </g>
  <rect id="shadow-center" x="{x0 + C}" y="{C}" width="{EDGE}" height="{EDGE}" opacity="0.001" fill="#000000" />
  <g id="shadow-right" transform="translate({x0 + C + EDGE}, {C})">
    <rect x="0" y="0" width="{R}" height="{EDGE}" opacity="0.001" fill="#000000" />
    <rect x="{R}" y="0" width="{SHADOW}" height="{EDGE}" fill="url(#sh-right-grad)" />
  </g>
  <g id="shadow-bottomleft" transform="translate({x0}, {C + EDGE})">
    <path fill="url(#sh-radial-bl)" d="M 0,0 H {SHADOW} A {R} {R} 0 0 0 {C},{R} V {C} H 0 Z" />
    <path d="M {SHADOW},0 A {R} {R} 0 0 0 {C},{R} V 0 Z" opacity="0.001" fill="#000000" />
  </g>
  <g id="shadow-bottom" transform="translate({x0 + C}, {C + EDGE})">
    <rect x="0" y="0" width="{EDGE}" height="{R}" opacity="0.001" fill="#000000" />
    <rect x="0" y="{R}" width="{EDGE}" height="{SHADOW}" fill="url(#sh-bottom-grad)" />
  </g>
  <g id="shadow-bottomright" transform="translate({x0 + C + EDGE}, {C + EDGE})">
    <path fill="url(#sh-radial-br)" d="M {R},0 H {C} V {C} H 0 V {R} A {R} {R} 0 0 0 {R},0 Z" />
    <path d="M 0,0 H {R} A {R} {R} 0 0 1 0,{R} Z" opacity="0.001" fill="#000000" />
  </g>
  <rect id="shadow-hint-top-margin" x="{x0 + C + EDGE // 2 - 4}" y="0" width="8" height="{SHADOW}" fill="none" opacity="0.001" />
  <rect id="shadow-hint-bottom-margin" x="{x0 + C + EDGE // 2 - 4}" y="{2 * C + EDGE - SHADOW}" width="8" height="{SHADOW}" fill="none" opacity="0.001" />
  <rect id="shadow-hint-left-margin" x="{x0}" y="{C + EDGE // 2 - 4}" width="{SHADOW}" height="8" fill="none" opacity="0.001" />
  <rect id="shadow-hint-right-margin" x="{x0 + 2 * C + EDGE - SHADOW}" y="{C + EDGE // 2 - 4}" width="{SHADOW}" height="8" fill="none" opacity="0.001" />
  <rect id="shadow-hint-top-inset" x="{x0 + C + EDGE // 2}" y="0" width="8" height="{SHADOW}" fill="none" opacity="0.001" />
  <rect id="shadow-hint-bottom-inset" x="{x0 + C + EDGE // 2}" y="{2 * C + EDGE - SHADOW}" width="8" height="{SHADOW}" fill="none" opacity="0.001" />
  <rect id="shadow-hint-left-inset" x="{x0}" y="{C + EDGE // 2}" width="{SHADOW}" height="8" fill="none" opacity="0.001" />
  <rect id="shadow-hint-right-inset" x="{x0 + 2 * C + EDGE - SHADOW}" y="{C + EDGE // 2}" width="{SHADOW}" height="8" fill="none" opacity="0.001" />
</svg>
'''
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--radius", type=int, default=12)
    ap.add_argument("files", nargs="+")
    a = ap.parse_args()
    for path in a.files:
        src = open(path, encoding="utf-8").read()
        style = re.search(r'<style[^>]*id="current-color-scheme".*?</style>', src, re.S).group(0)
        op = re.search(r'id="center"[^>]*fill-opacity:\s*([0-9.]+)', src, re.S)
        open(path, "w", encoding="utf-8").write(build(style, op.group(1) if op else "1.0", a.radius))
        print("wrote", path, "opacity", op.group(1) if op else "1.0")


if __name__ == "__main__":
    main()
